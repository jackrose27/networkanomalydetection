"""Inference for the two-tier UNSW-NB15 network-flow classifier.

The LightGBM models and metadata are generated by the training notebook.
Load only model files that you trained or otherwise trust.
"""

from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parent
MODEL_DIR = PROJECT_ROOT / "models"


@dataclass
class ModelBundle:
    tier1: object
    tier2: object
    metadata: dict


@lru_cache(maxsize=1)
def load_models() -> ModelBundle:
    paths = {
        "Tier 1 model": MODEL_DIR / "tier1_lightgbm.joblib",
        "Tier 2 model": MODEL_DIR / "tier2_lightgbm.joblib",
        "metadata": MODEL_DIR / "metadata.joblib",
    }
    missing = [str(path) for path in paths.values() if not path.exists()]
    if missing:
        raise FileNotFoundError(
            "The saved model files are missing. Copy the three files produced "
            "by Step 13 of your notebook into models/: " + ", ".join(missing)
        )

    return ModelBundle(
        tier1=joblib.load(paths["Tier 1 model"]),
        tier2=joblib.load(paths["Tier 2 model"]),
        metadata=joblib.load(paths["metadata"]),
    )


def prepare_features(data: pd.DataFrame, metadata: dict) -> pd.DataFrame:
    """Reproduce the LightGBM feature types from training (no refitting)."""
    required = metadata["feature_columns"]
    missing = [name for name in required if name not in data.columns]
    if missing:
        raise ValueError(
            f"CSV is missing {len(missing)} required feature(s): "
            + ", ".join(missing)
        )

    features = data.loc[:, required].copy()  # preserve training order
    categoricals = set(metadata["categorical_features"])

    for col in required:
        if col in categoricals:
            levels = metadata["categorical_levels"][col]
            # Unseen categories become NaN, matching training-time transform.
            features[col] = pd.Categorical(
                features[col].astype("string").fillna("nan"),
                categories=levels,
            )
        else:
            try:
                features[col] = pd.to_numeric(features[col], errors="raise")
            except (ValueError, TypeError) as exc:
                raise ValueError(
                    f"Column '{col}' must be numeric. Check the CSV values."
                ) from exc

    return features


def predict_dataframe(data: pd.DataFrame, models: ModelBundle | None = None) -> pd.DataFrame:
    """Return a row-aligned output with model labels and Tier 1 scores."""
    if models is None:
        models = load_models()
    if data.empty:
        raise ValueError("The CSV contains no rows.")

    features = prepare_features(data, models.metadata)
    threshold = float(models.metadata["threshold"])

    tier1_scores = np.asarray(models.tier1.predict_proba(features))[:, 1]
    flagged = tier1_scores >= threshold

    classes = np.full(len(data), "Normal", dtype=object)
    if flagged.any():
        family_preds = np.asarray(
            models.tier2.predict(features.iloc[np.flatnonzero(flagged)])
        ).ravel()
        classes[flagged] = family_preds.astype(str)

    result = data.copy()
    result["Tier1_Attack_Score"] = tier1_scores
    result["Tier1_Prediction"] = np.where(flagged, "Attack", "Normal")
    result["Predicted_Class"] = classes
    return result
